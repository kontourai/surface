// Builds the Trust Panel's copy of @kontourai/ui/trust-state.css.
//
// The panel renders in a shadow root and must stay legible on a page that
// defines no Kontour tokens, so each var() in ui's chip rules gets ui's
// light-mode token value as its fallback (the panel's own fallback palette is
// light). A page that loads @kontourai/ui/tokens gets its own mode and theme.
// Comments are dropped to keep the panel bundle small; the rules, their
// order, and their declarations are ui's. `--check` fails when the checked-in
// module differs from what the installed @kontourai/ui produces.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const kitRoot = path.join(root, "node_modules", "@kontourai", "ui");
const generatedPath = path.join(root, "src", "trust-panel", "trust-state-css.generated.ts");
const checkOnly = process.argv.includes("--check");

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");
const [chipCss, tokensCss] = await Promise.all([
  readFile(path.join(kitRoot, "react", "trust-state.css"), "utf8").then(stripComments),
  readFile(path.join(kitRoot, "tokens", "tokens.css"), "utf8").then(stripComments),
]);

function tokenBlock(pattern) {
  const block = tokensCss.match(pattern);
  if (!block) throw new Error(`@kontourai/ui tokens.css has no block matching ${pattern}`);
  const tokens = new Map();
  for (const declaration of block[1].split(";")) {
    const match = declaration.match(/(--k-[\w-]+)\s*:\s*([\s\S]+)/);
    if (match) tokens.set(match[1], match[2].trim().replace(/\s+/g, " "));
  }
  return tokens;
}
const dark = tokenBlock(/:root\s*\{([^}]*)\}/);
const light = tokenBlock(/\[data-theme="light"\]\s*\{([^}]*)\}/);

const rules = [...chipCss.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selector, body]) => {
  const declarations = body
    .split(";")
    .map((declaration) => declaration.trim().replace(/\s+/g, " "))
    .filter(Boolean)
    .map((declaration) =>
      declaration.replace(/var\((--k-[\w-]+)\)/g, (_whole, name) => {
        const value = light.get(name) ?? dark.get(name);
        if (!value) throw new Error(`@kontourai/ui defines no value for ${name}`);
        return `var(${name}, ${value})`;
      }),
    );
  return `${selector.trim().replace(/\s+/g, " ")} { ${declarations.join("; ")}; }`;
});
if (!rules.some((rule) => rule.startsWith(".trust-state--verified "))) {
  throw new Error("@kontourai/ui/trust-state.css has no trust-state rules.");
}

const generated = [
  "// Generated by scripts/build-trust-state-css.mjs from @kontourai/ui/trust-state.css.",
  "// Do not edit directly; bump @kontourai/ui and run npm run build:trust-state-css.",
  "/* eslint-disable */",
  `export const TRUST_STATE_PANEL_CSS: string = ${JSON.stringify(rules.join("\n"))};`,
  "",
].join("\n");

if (checkOnly) {
  const current = await readFile(generatedPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error("The Trust Panel's trust-state CSS is out of sync with @kontourai/ui. Run npm run build:trust-state-css.");
  }
  console.log("Trust Panel trust-state CSS is synced with @kontourai/ui.");
} else {
  await writeFile(generatedPath, generated);
  console.log("Built Trust Panel trust-state CSS.");
}
